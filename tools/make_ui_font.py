#!/usr/bin/env python3
"""make_ui_font.py — rasterises the UI fonts into firmware/panel/font_ui.c.
Font: Liberation Sans Bold (SIL Open Font License 1.1, metric-compatible with Helvetica), tools/fonts/.
Three sizes from the Roffa Logics design: 14 px (main menu, intro), 13 px (option), 8 px (caption).
Each glyph is a cell of <advance> x <line height> pixels, 1 bit per pixel, rows as uint16 (bit 15 = left)."""
import os, sys
from PIL import Image, ImageDraw, ImageFont
HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, 'fonts', 'LiberationSans-Bold.ttf')
OUT = os.path.join(HERE, '..', 'firmware', 'panel')
SIZES = [(14, 'ui_font14', 140), (13, 'ui_font13', 140), (8, 'ui_font8', 110)]   # size, symbol, grey threshold (lower = bolder)

def glyphs(size, thr):
    ft = ImageFont.truetype(TTF, size); asc, desc = ft.getmetrics(); h = asc + desc
    out = []
    for code in range(32, 127):
        ch = chr(code); adv = max(1, int(round(ft.getlength(ch))))
        im = Image.new('L', (adv + 4, h), 0); ImageDraw.Draw(im).text((1, 0), ch, font=ft, fill=255)   # antialiased, then thresholded: cleaner than the mono hinter at these sizes
        px = im.load(); cols = [x for x in range(adv + 4) if any(px[x, y] >= thr for y in range(h))]
        if cols: x0, x1 = cols[0], cols[-1]; w = x1 - x0 + 1
        else: x0, w = 0, 0
        cell = (w + 1) if w else max(2, adv - 1)                                                # tight: ink width + 1 px (the design's bold, compact look; side bearings dropped)
        if cell > 16: cell = 16
        rows = []
        for y in range(h):
            v = 0
            for x in range(min(w, 16)):
                if px[x0 + x, y] >= thr: v |= 0x8000 >> x
            rows.append(v)
        out.append((cell, rows))
    return h, asc, out

c = ['/* Generated by tools/make_ui_font.py - do not edit. Liberation Sans Bold, SIL OFL 1.1. */', '#include "font_ui.h"']
for size, sym, thr in SIZES:
    h, asc, gl = glyphs(size, thr)
    c.append(f'static const uint8_t {sym}_w[95] = {{ ' + ', '.join(str(g[0]) for g in gl) + ' };')
    c.append(f'static const uint16_t {sym}_rows[95][{h}] = {{')
    for i, g in enumerate(gl): c.append('  { ' + ', '.join('0x%04X' % r for r in g[1]) + ' },' + f'   /* {chr(32+i) if 32+i != 92 else "backslash"} */')
    c.append('};')
    c.append(f'const ui_font_t {sym} = {{ {h}, {asc}, {sym}_w, (const uint16_t *){sym}_rows }};')
import math
N, D = 12, 20
c.append(f'/* loading spinner: {N} frames of a 270-degree ring, {D}x{D}, rows as uint32 (bit 31 = left) */')
c.append(f'const uint32_t ui_spinner[{N}][{D}] = {{')
for fr in range(N):
    rows = []
    for y in range(D):
        v = 0
        for x in range(D):
            dx, dy = x - (D - 1) / 2, y - (D - 1) / 2; r = math.hypot(dx, dy)
            a = (math.degrees(math.atan2(dy, dx)) - fr * 360 / N) % 360
            if 5.6 <= r <= 9.6 and a < 270: v |= 0x80000000 >> x
        rows.append(v)
    c.append('  { ' + ', '.join('0x%08X' % r for r in rows) + ' },')
c.append('};')
open(os.path.join(OUT, 'font_ui.c'), 'w').write('\n'.join(c) + '\n')
open(os.path.join(OUT, 'font_ui.h'), 'w').write('''/* UI fonts (proportional, mixed case). Generated data in font_ui.c; see tools/make_ui_font.py. */
#ifndef FONT_UI_H
#define FONT_UI_H
#include <stdint.h>
typedef struct { uint8_t height, ascent; const uint8_t *width; const uint16_t *rows; } ui_font_t;   /* glyphs 32..126; rows[glyph * height + y] */
extern const ui_font_t ui_font14, ui_font13, ui_font8;\n#define UI_SPINNER_FRAMES 12\n#define UI_SPINNER_SIZE 20\nextern const uint32_t ui_spinner[UI_SPINNER_FRAMES][UI_SPINNER_SIZE];
#endif
''')
print('fonts written')
